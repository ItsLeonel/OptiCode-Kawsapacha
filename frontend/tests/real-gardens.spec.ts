test('catálogo oficial íntegro y selectores dependientes con búsqueda', async ({ page }) => {
  const provinces = new Set(catalogue.provinces.map(item => item.code))
  const cantons = new Map(catalogue.cantons.map(item => [item.code, item]))
  expect(provinces.size).toBe(24)
  expect(cantons.size).toBe(catalogue.cantons.length)
  for (const canton of cantons.values()) expect(provinces.has(canton.provinceCode)).toBe(true)
  expect(new Set(catalogue.parishes.map(item => item.code)).size).toBe(catalogue.parishes.length)
  for (const parish of catalogue.parishes) expect(cantons.has(parish.cantonCode)).toBe(true)
  await openGarden(page)
  await expect(page.getByRole('combobox', { name: 'Cantón' })).toBeDisabled()
  await page.locator('#rg-province').selectOption('Imbabura')
  const canton = page.getByRole('combobox', { name: 'Cantón' })
  await canton.click()
  await expect(page.locator('.rg-select-popover').getByRole('option')).toHaveCount(6)
  const expected = catalogue.cantons.filter(item => item.provinceCode === '10').map(item => item.code).sort()
  expect((await page.locator('.rg-select-popover').getByRole('option').allTextContents()).map(text => text.trim().slice(-4)).sort()).toEqual(expected)
  await canton.fill('ibarra')
  await canton.press('ArrowDown')
  await canton.press('Enter')
  await expect(canton).toHaveValue('Ibarra')
  const parish = page.getByRole('combobox', { name: 'Parroquia' })
  await parish.fill('san antonio')
  await page.getByRole('option', { name: /^San Antonio / }).click()
  await expect(parish).toHaveValue('San Antonio')
  await page.locator('#rg-province').selectOption('Pichincha')
  await expect(canton).toHaveValue('')
  await expect(parish).toHaveValue('')
  await expect(parish).toBeDisabled()
  await canton.fill('mejia')
  await expect(page.getByRole('option', { name: /^Mejía / })).toBeVisible()
  await canton.press('Enter')
  await parish.click()
  await expect(page.locator('.rg-select-popover').getByRole('option')).toHaveCount(catalogue.parishes.filter(item => item.cantonCode === '1703').length)
})

test('marcador por clic y arrastre, zoom, teclado, cancelación y guardado', async ({ page }) => {
  const pageErrors: string[] = []
  page.on('pageerror', error => pageErrors.push(error.message))
  await openGarden(page)
  await fillEssentials(page)
  await page.getByRole('button', { name: 'Marcar mi huerto en el mapa', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const map = dialog.locator('.rg-detail-map')
  await expect(dialog.getByRole('link', { name: 'OpenStreetMap' })).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Usar esta ubicación' })).toBeDisabled()
  await map.click({ position: { x: 300, y: 170 } })
  const before = await dialog.locator('.rg-map-selection').innerText()
  const marker = dialog.locator('.rg-map-marker')
  const box = await marker.boundingBox()
  if (!box) throw new Error('El marcador no es visible')
  await page.mouse.move(box.x + 16, box.y + 14)
  await page.mouse.down()
  await page.mouse.move(box.x + 75, box.y + 50, { steps: 12 })
  await page.mouse.up()
  await expect(dialog.locator('.rg-map-selection')).not.toHaveText(before)
  await dialog.locator('.leaflet-control-zoom-in').click()
  await map.focus()
  await map.press('ArrowRight')
  await dialog.getByRole('button', { name: 'Marcar el centro del mapa' }).click()
  const chosen = await dialog.locator('.rg-map-selection').innerText()
  await page.screenshot({ path: test.info().outputPath('marcador.png'), fullPage: true })
  await dialog.getByRole('button', { name: 'Usar esta ubicación' }).click()
  await expect(page.locator('.rg-coordinate-value')).toContainText(chosen.replace('Latitud, longitud: ', ''))
  await page.getByRole('button', { name: 'Ajustar ubicación en el mapa' }).click()
  await map.click({ position: { x: 350, y: 220 } })
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(page.locator('.rg-coordinate-value')).toContainText(chosen.replace('Latitud, longitud: ', ''))
  await page.getByRole('button', { name: 'Guardar mi huerto', exact: true }).click()
  await expect(page.locator('.rg-summary')).toContainText(chosen.replace('Latitud, longitud: ', ''))
  await expect(page.locator('.rg-summary')).toContainText('sin verificar')
  await expect(page.locator('.rg-form')).toHaveCount(0)
  await page.getByRole('button', { name: 'Editar mi huerto', exact: true }).click()
  await expect(page.locator('.rg-coordinate-value')).toContainText(chosen.replace('Latitud, longitud: ', ''))
  await page.getByRole('button', { name: 'Cancelar edición' }).click()
  await expect(page.locator('.rg-summary')).toContainText(chosen.replace('Latitud, longitud: ', ''))
  expect(pageErrors).toEqual([])
})

