test('movimiento reducido, foco y contraste del botón del marcador', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await openGarden(page)
  await page.locator('#rg-province').selectOption('Napo')
  await expect(page.locator('.rg-regional-layer.is-active')).toHaveCSS('opacity', '1')
  for (const layer of await page.locator('.rg-regional-layer').all()) await expect(layer).toHaveCSS('transition-duration', '0s')
  const button = page.getByRole('button', { name: 'Marcar mi huerto en el mapa', exact: true })
  await button.focus()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Shift+Tab')
  await expect(button).toBeFocused()
  await expect(button).toHaveCSS('outline-style', 'solid')
  const minimumContrast = await button.evaluate(element => {
    const style = getComputedStyle(element)
    function luminance(rgb: number[]) {
      const linear = rgb.map(value => value / 255).map(value => value <= .04045 ? value / 12.92 : ((value + .055) / 1.055) ** 2.4)
      return linear[0] * .2126 + linear[1] * .7152 + linear[2] * .0722
    }
    const text = luminance(style.color.match(/[\d.]+/g)!.slice(0, 3).map(Number))
    const colors = [...style.backgroundImage.matchAll(/rgb\(([^)]+)\)/g)]
    if (colors.length !== 2) return NaN
    return Math.min(...colors.map(match => {
      const background = luminance(match[1].split(',').map(Number))
      return (Math.max(text, background) + .05) / (Math.min(text, background) + .05)
    }))
  })
  expect(Number.isFinite(minimumContrast)).toBe(true)
  expect(minimumContrast).toBeGreaterThanOrEqual(4.5)
  await button.hover()
  await expect(button).toHaveCSS('transform', 'none')
  await button.press('Enter')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('dialog').press('Escape')
  await expect(button).toBeFocused()
})
