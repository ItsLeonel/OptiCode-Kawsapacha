import { test, expect, type Page } from '@playwright/test'

test.use({ launchOptions: { args: ['--use-fake-device-for-media-stream'] } })

const PHOTO = 'src/features/real-gardens/assets/en-tierra-v1.jpg'
const nav = (page: Page) => page.getByRole('navigation', { name: 'Navegación principal' })
const actions = (page: Page) => page.getByRole('navigation', { name: 'Acciones de tu jardín' })
const registration = (page: Page) => page.getByRole('dialog', { name: 'Registrar planta', exact: true })
const pageErrors = new WeakMap<Page, string[]>()

test.beforeEach(async ({ page }) => {
  const errors: string[] = []
  pageErrors.set(page, errors)
  page.on('pageerror', error => errors.push(error.message))
  // Only map tiles and the camera device are fixtures; records use the real UI and App state.
  await page.route('https://tile.openstreetmap.org/**', route => route.fulfill({
    contentType: 'image/png',
    body: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j5N8AAAAASUVORK5CYII=', 'base64'),
  }))
  await page.goto('/')
  await page.getByRole('button', { name: 'Descubrir Kawsapacha' }).click()
})

test.afterEach(async ({ page }) => { expect(pageErrors.get(page)).toEqual([]) })

async function fillGarden(page: Page) {
  await page.locator('#rg-province').selectOption('Imbabura')
  await page.getByLabel('Nombre del huerto').fill('Huerto de la minga')
  await page.getByLabel('Superficie aproximada').fill('25')
  await page.getByRole('combobox', { name: 'Cantón' }).fill('Ibarra')
  await page.getByRole('option', { name: /^Ibarra / }).click()
  await page.getByRole('combobox', { name: 'Parroquia' }).fill('San Antonio')
  await page.getByRole('option', { name: /^San Antonio / }).click()
  await page.locator('.rg-type-option:has(input[value="ground"])').click()
  if (!(await page.getByLabel('Agua de riego').isVisible())) await page.locator('.rg-more-characteristics summary').click()
  await page.getByLabel('Agua de riego').selectOption('available')
  await page.getByLabel('Tipo de suelo').selectOption('loam')
}

async function assertFits(page: Page, dialog = false) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  if (dialog) {
    expect(await page.getByRole('dialog').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  }
}

async function closePassport(page: Page) {
  await page.getByRole('button', { name: 'Cerrar Pasaporte Vivo' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
}

for (const scenario of [
  { name: 'escritorio y galería', width: 1440, height: 1000, camera: false },
  { name: 'móvil y cámara', width: 390, height: 844, camera: true },
]) {
  test.describe(scenario.name, () => {
    test.use({
      viewport: { width: scenario.width, height: scenario.height },
      hasTouch: scenario.camera,
      permissions: ['camera'],
    })

    test('comunidad y huerto editables → planta → espacio → Pasaporte → navegación de la visita', async ({ page }) => {
      test.setTimeout(90_000)
      await nav(page).getByRole('button', { name: 'Comunidad', exact: true }).click()
      await page.getByRole('button', { name: 'Crear mi comunidad', exact: true }).click()
      await page.getByRole('button', { name: 'Crear comunidad', exact: true }).click()
      await expect(page.getByRole('alert')).toContainText('entre 3 y 80 caracteres')
      await expect(page.getByLabel('Nombre de la comunidad')).toBeFocused()
      await page.getByLabel('Nombre de la comunidad').fill('  Comunidad de la minga  ')
      await page.getByLabel('Persona responsable').fill('Ana')
      await page.getByLabel('Localidad o provincia').fill('San Antonio, Imbabura')
      await page.getByLabel('Acerca de la comunidad').fill('Cultivamos plantas y compartimos saberes.')
      await assertFits(page, true)
      await page.getByRole('button', { name: 'Crear comunidad', exact: true }).click()
      const community = page.getByRole('region', { name: 'Mi comunidad registrada' })
      await expect(community.getByRole('heading', { name: 'Comunidad de la minga', exact: true })).toBeVisible()
      await page.getByRole('button', { name: 'Editar comunidad', exact: true }).click()
      await page.getByLabel('Nombre de la comunidad').fill('Cambio descartado')
      await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
      await expect(community).not.toContainText('Cambio descartado')
      await page.getByRole('button', { name: 'Editar comunidad', exact: true }).click()
      await page.getByLabel('Nombre de la comunidad').fill('Comunidad Kawsapacha')
      await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
      await expect(community).toContainText('Comunidad Kawsapacha')
      await page.screenshot({ path: test.info().outputPath('comunidad.png'), fullPage: true })
      await community.getByRole('button', { name: 'Registrar huerto compartido' }).click()

      await page.getByRole('button', { name: 'Guardar mi huerto', exact: true }).click()
      await expect(page.locator('#rg-province')).toBeFocused()
      await expect(page.getByRole('status')).toContainText('Revisa los campos indicados')
      await expect(page.getByRole('status')).toBeVisible()
      await fillGarden(page)
      await page.getByRole('button', { name: 'Marcar mi huerto en el mapa' }).click()
      await page.getByRole('button', { name: 'Marcar el centro del mapa' }).click()
      const coordinates = (await page.locator('.rg-map-selection').innerText()).replace('Latitud, longitud: ', '')
      await page.getByRole('button', { name: 'Usar esta ubicación' }).click()
      await page.getByRole('button', { name: 'Guardar mi huerto', exact: true }).click()
      await expect(page.locator('.rg-summary')).toContainText('Comunidad Kawsapacha')
      await expect(page.locator('.rg-summary')).toContainText(coordinates)
      await page.getByRole('button', { name: 'Editar mi huerto', exact: true }).click()
      await page.getByLabel('Nombre del huerto').fill('Huerto Kawsapacha')
      await page.getByLabel('Superficie aproximada').fill('30')
      await page.locator('.rg-type-option:has(input[value="vertical"])').click()
      await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
      await expect(page.locator('.rg-summary')).toContainText('30 m²')
      await expect(page.locator('.rg-summary')).toContainText(coordinates)
      await assertFits(page)
      await page.screenshot({ path: test.info().outputPath('huerto.png'), fullPage: true })
      await page.getByRole('button', { name: 'Conectar con Mi Jardín' }).click()
      await expect(page.locator('.my-garden-page')).toHaveAttribute('data-garden-kind', 'vertical')
      await expect(page.getByLabel('Ubicación de tu huerto')).toContainText('Huerto Kawsapacha')

      await page.locator('.garden-parcels button').nth(4).click()
      await expect(page.getByLabel('Posición de cultivo')).toHaveValue('4')
      if (scenario.camera) {
        await page.getByRole('button', { name: 'Cámara', exact: true }).click()
        await page.getByRole('button', { name: 'Tomar fotografía' }).click()
      } else {
        const chooser = page.waitForEvent('filechooser')
        await page.getByRole('button', { name: 'Galería', exact: true }).click()
        await (await chooser).setFiles(PHOTO)
      }
      await expect(page.getByAltText('Vista previa de tu planta', { exact: true })).toBeVisible()
      await page.getByLabel('Especie medicinal').selectOption('Manzanilla')
      await page.getByLabel('Fecha de siembra').fill('2026-11-01')
      await assertFits(page, true)
      await page.getByRole('button', { name: 'Añadir a mi huerto' }).click()
      const passport = page.getByRole('dialog', { name: 'Manzanilla', exact: true })
      await expect(passport).toBeVisible()
      await expect(passport).toContainText('Matricaria chamomilla')
      await expect(passport).toContainText('Parcela 5')
      await expect(passport).toContainText('1/11/2026')
      const photo = await page.locator('.garden-passport-photo').getAttribute('src')
      expect(photo).toMatch(/^blob:/)
      expect(await page.locator('.garden-passport-photo').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
      await assertFits(page, true)
      await page.screenshot({ path: test.info().outputPath('pasaporte.png'), fullPage: true })
      await closePassport(page)
      const plantedSpace = page.locator('.garden-parcels button').nth(4)
      await expect(plantedSpace).toBeFocused()
      await expect(plantedSpace.locator('img')).toHaveAttribute('src', photo!)
      await expect(page.locator('.garden-parcel.is-occupied')).toHaveCount(1)

      await nav(page).getByRole('button', { name: 'Descubrir plantas', exact: true }).click()
      await page.getByLabel('Buscar plantas').fill('especie inexistente')
      await expect(page.getByText('No se encontraron especies con ese nombre.')).toBeVisible()
      await assertFits(page)
      await page.goBack()
      await expect(plantedSpace.locator('img')).toHaveAttribute('src', photo!)
      await page.goForward()
      await expect(page.getByRole('heading', { name: 'Descubrir plantas', exact: true })).toBeVisible()
      await nav(page).getByRole('button', { name: 'Mi historia', exact: true }).click()
      await assertFits(page)
      await page.getByRole('button', { name: /Abrir Pasaporte Vivo/ }).click()
      await expect(page.locator('.garden-passport-photo')).toHaveAttribute('src', photo!)
      await page.getByRole('button', { name: 'Ver Bitácora de cultivo' }).click()
      await expect(passport).not.toBeVisible()
      await nav(page).getByRole('button', { name: 'Mi Huerto', exact: true }).click()
      await expect(page.locator('.rg-summary')).toContainText('Huerto Kawsapacha')
      await nav(page).getByRole('button', { name: 'Comunidad', exact: true }).click()
      await expect(community).toContainText('Comunidad Kawsapacha')
      await expect(community).toContainText('Huerto Kawsapacha')
      await page.getByRole('button', { name: 'Volver a bienvenida', exact: true }).click()
      await page.getByRole('button', { name: 'Descubrir Kawsapacha' }).click()
      await expect(plantedSpace.locator('img')).toHaveAttribute('src', photo!)
      await plantedSpace.click()
      await expect(page.locator('.garden-passport-photo')).toHaveAttribute('src', photo!)
      await closePassport(page)
      await assertFits(page)
      await page.reload()
      await page.getByRole('button', { name: 'Descubrir Kawsapacha' }).click()
      await expect(page.locator('.garden-start')).toBeVisible()
      await expect(page.locator('.garden-parcel.is-occupied')).toHaveCount(0)
    })
  })
}

test('sin huerto: pausa y recupera fotografía, especie, espacio y fecha al conectar, sin comunidad', async ({ page }) => {
  await nav(page).getByRole('button', { name: 'Descubrir plantas', exact: true }).click()
  await page.locator('.species-card').filter({ hasText: 'Lavanda' }).getByRole('button').click()
  await page.locator('#plant-photo').setInputFiles(PHOTO)
  await page.getByLabel('Posición de cultivo').selectOption('3')
  await page.getByLabel('Fecha de siembra').fill('2026-10-30')
  await expect(page.getByRole('button', { name: 'Añadir a mi huerto' })).toBeDisabled()
  await page.getByRole('button', { name: 'Ir a Mi Huerto', exact: true }).click()
  await expect(page.getByText('Tu planta está en pausa.', { exact: false })).toBeVisible()
  await fillGarden(page)
  await nav(page).getByRole('button', { name: 'Mi jardín', exact: true }).click()
  await page.goBack()
  await expect(page.getByLabel('Nombre del huerto')).toHaveValue('Huerto de la minga')
  await page.getByRole('button', { name: 'Guardar mi huerto', exact: true }).click()
  await page.getByRole('button', { name: 'Conectar con Mi Jardín' }).click()
  await expect(registration(page)).toBeVisible()
  await expect(page.getByLabel('Especie medicinal')).toHaveValue('Lavanda')
  await expect(page.getByLabel('Posición de cultivo')).toHaveValue('3')
  await expect(page.getByLabel('Fecha de siembra')).toHaveValue('2026-10-30')
  await expect(page.getByAltText('Vista previa de tu planta', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Añadir a mi huerto' }).click()
  await expect(page.getByRole('dialog', { name: 'Lavanda', exact: true })).toBeVisible()
  await expect(page.getByRole('dialog')).toContainText('Parcela 4')
  await closePassport(page)
  await expect(page.locator('.garden-parcel.is-occupied')).toHaveCount(1)
})

test('edición inválida y cancelación conservan comunidad, huerto y planta registrados', async ({ page }) => {
  await nav(page).getByRole('button', { name: 'Comunidad', exact: true }).click()
  await page.getByRole('button', { name: 'Crear mi comunidad', exact: true }).click()
  await page.getByLabel('Nombre de la comunidad').fill('Comunidad original')
  await page.getByRole('button', { name: 'Crear comunidad', exact: true }).click()
  await nav(page).getByRole('button', { name: 'Mi Huerto', exact: true }).click()
  await fillGarden(page)
  await page.getByRole('button', { name: 'Guardar mi huerto', exact: true }).click()
  await page.getByRole('button', { name: 'Conectar con Mi Jardín' }).click()
  await page.locator('.garden-parcels button').nth(0).click()
  await page.locator('#plant-photo').setInputFiles(PHOTO)
  await page.getByRole('button', { name: 'Añadir a mi huerto' }).click()
  const photo = await page.locator('.garden-passport-photo').getAttribute('src')
  await closePassport(page)
  await nav(page).getByRole('button', { name: 'Mi Huerto', exact: true }).click()
  await page.getByRole('button', { name: 'Editar mi huerto', exact: true }).click()
  await page.getByLabel('Nombre del huerto').fill('  ')
  await page.getByLabel('Superficie aproximada').fill('0')
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(page.getByLabel('Nombre del huerto')).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByLabel('Superficie aproximada')).toHaveAttribute('aria-invalid', 'true')
  await page.getByRole('button', { name: 'Cancelar edición' }).click()
  await expect(page.locator('.rg-summary')).toContainText('Huerto de la minga')
  await expect(page.locator('.rg-summary')).toContainText('25 m²')
  await nav(page).getByRole('button', { name: 'Comunidad', exact: true }).click()
  await page.getByRole('button', { name: 'Editar comunidad', exact: true }).click()
  await page.getByLabel('Nombre de la comunidad').fill('  ')
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('region', { name: 'Mi comunidad registrada' })).toContainText('Comunidad original')
  await nav(page).getByRole('button', { name: 'Mi jardín', exact: true }).click()
  await expect(page.locator('.garden-parcel-photo img')).toHaveAttribute('src', photo!)
  await actions(page).getByRole('button', { name: 'Registrar planta', exact: true }).click()
  await expect(page.getByLabel('Posición de cultivo').locator('option[value="0"]')).toHaveJSProperty('disabled', true)
  await page.locator('#plant-photo').setInputFiles({ name: 'rota.jpg', mimeType: 'image/jpeg', buffer: Buffer.from('imagen dañada') })
  await expect(page.getByRole('alert')).toContainText('No se puede leer esta imagen')
  await expect(page.getByRole('button', { name: 'Añadir a mi huerto' })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(page.locator('.garden-parcel.is-occupied')).toHaveCount(1)
})
