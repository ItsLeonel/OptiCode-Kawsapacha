async function openGarden(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Descubrir Kawsapacha' }).click()
  await createCommunity(page)
  await page.getByRole('navigation', { name: 'Navegación principal' }).getByRole('button', { name: 'Mi Huerto', exact: true }).click()
  await expect(page.locator('.map-visual path[role="button"]')).toHaveCount(24)
}

async function fillEssentials(page: Page, kind = 'pots') {
  await page.locator('#rg-province').selectOption('Imbabura')
  await page.getByLabel('Nombre del huerto').fill('Huerto de prueba')
  await page.getByLabel('Superficie aproximada').fill('25')
  await page.locator(`.rg-type-option:has(input[value="${kind}"])`).click()
  if (!(await page.getByLabel('Agua de riego').isVisible())) await page.locator('.rg-more-characteristics > summary').click()
  await page.getByLabel('Agua de riego').selectOption('available')
  if (kind === 'ground') await page.getByLabel('Tipo de suelo').selectOption('loam')
}

