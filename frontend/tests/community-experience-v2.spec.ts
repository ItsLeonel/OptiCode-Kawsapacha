import { test, expect, type Page } from './e2e'
import catalogue from '../src/features/real-gardens/data/dpa-2026.json' with { type: 'json' }
import { chooseCommunityTerritory, createCommunity, mainNavigation, nextCommunityStep } from './community-helpers'

test.setTimeout(60_000)
const browserErrors = new WeakMap<Page,string[]>()
test.beforeEach(async ({page}) => {
  browserErrors.set(page,[])
  page.on('pageerror',error=>browserErrors.get(page)!.push(error.message))
  await page.goto('/')
  await page.getByRole('button',{name:'Descubrir Kawsapacha'}).click()
  await mainNavigation(page).getByRole('button',{name:'Comunidad',exact:true}).click()
  await page.getByRole('button',{name:'Crear mi comunidad',exact:true}).click()
})
test.afterEach(async ({page}) => expect(browserErrors.get(page)).toEqual([]))

async function chooseCode(page:Page,label:string,code:string) {
  const option = (label === 'Cantón' ? catalogue.cantons : catalogue.parishes).find(item=>item.code===code)!
  await page.getByRole('combobox',{name:label}).fill(option.name)
  await page.getByRole('option',{name:new RegExp(`${code}$`)}).click()
}
async function fillIdentity(page:Page,name='Raíces de la minga') {
  await page.getByRole('button',{name:'Editar identidad',exact:true}).click()
  await page.getByLabel('Nombre de la comunidad').fill(name)
  await page.getByLabel('Acerca de la comunidad').fill('Cultivamos y compartimos saberes en nuestro barrio.')
}
async function fillResponsible(page:Page) {
  await page.getByRole('button',{name:'Editar responsable',exact:true}).click()
  await page.getByLabel('Persona responsable').fill('Ana Molina')
  await page.getByLabel('Teléfono').fill('+593 999 123 456')
  await page.getByLabel('Correo electrónico').fill('ana@example.com')
}
async function noOverflow(page:Page) {
  expect(await page.locator('.community-wizard').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
}
async function capture(page:Page,path:string) {
  await page.locator('.community-wizard img').evaluateAll(images=>Promise.all(images.map(img=>(img as HTMLImageElement).decode())))
  await page.locator('.community-wizard').evaluate(async el=>{
    el.querySelector<HTMLElement>('.community-close')?.focus({preventScroll:true})
    el.scrollTo({top:0,behavior:'instant'})
    await new Promise<void>(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve())))
  })
  await expect.poll(()=>page.locator('.community-wizard').evaluate(el=>el.scrollTop)).toBe(0)
  await noOverflow(page)
  await page.screenshot({path})
}

test('catálogo jerárquico, búsqueda por teclado y limpieza de provincia/cantón',async({page})=>{
  await nextCommunityStep(page)
  const canton=page.getByRole('combobox',{name:'Cantón'})
  const parish=page.getByRole('combobox',{name:'Parroquia'})
  await expect(canton).toBeDisabled()
  await expect(parish).toBeDisabled()
  await page.getByLabel('Provincia de la comunidad').selectOption('Guayas')
  await canton.click()
  const allowed=catalogue.cantons.filter(item=>item.provinceCode==='09').map(item=>item.code).sort()
  expect((await page.locator('.cw-territory-controls .rg-select-popover').getByRole('option').allTextContents()).map(label=>label.trim().slice(-4)).sort()).toEqual(allowed)
  await canton.fill('guayaquil')
  await canton.press('ArrowDown')
  await canton.press('Enter')
  await expect(canton).toHaveValue('Guayaquil')
  await parish.click()
  expect((await page.locator('.cw-territory-controls .rg-select-popover').getByRole('option').allTextContents()).map(label=>label.trim().slice(-6)).sort()).toEqual(catalogue.parishes.filter(item=>item.cantonCode==='0901').map(item=>item.code).sort())
  await chooseCode(page,'Parroquia','090153')
  await page.getByLabel('Sector o barrio').fill('Las Flores')
  await chooseCode(page,'Cantón','0903')
  await expect(parish).toHaveValue('')
  await chooseCode(page,'Parroquia','090350')
  await page.getByLabel('Provincia de la comunidad').selectOption('Pichincha')
  await expect(canton).toHaveValue('')
  await expect(parish).toHaveValue('')
  await expect(parish).toBeDisabled()
  await expect(page.getByLabel('Sector o barrio')).toHaveValue('')
  await nextCommunityStep(page)
  await expect(page.getByRole('alert')).toContainText('cantón que pertenezca')
  await expect(canton).toBeFocused()
})

test('Guayas no acepta Quito como cantón y el hover no cambia el territorio elegido',async({page})=>{
  await page.setViewportSize({width:1366,height:768})
  await nextCommunityStep(page)
  await page.getByLabel('Provincia de la comunidad').selectOption('Guayas')
  await page.getByRole('combobox',{name:'Cantón'}).fill('Quito')
  await expect(page.getByText('No se encontraron coincidencias.',{exact:true})).toBeVisible()
  await expect(page.locator('.cw-territory-controls .rg-select-popover').getByRole('option')).toHaveCount(0)
  await nextCommunityStep(page)
  await expect(page.getByRole('alert')).toContainText('cantón que pertenezca')
  await expect(page.getByRole('button',{name:'Editar identidad',exact:true})).toHaveCount(0)
  await chooseCommunityTerritory(page,'Guayas','Las Flores')
  await page.getByRole('button',{name:'Seleccionar Pichincha',exact:true}).hover()
  await expect(page.locator('.map-province-tooltip')).toHaveAttribute('data-kind','preview')
  await expect(page.locator('.map-province-tooltip')).toHaveText('Explorando: Pichincha')
  await expect(page.getByRole('button',{name:'Seleccionar Guayas',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(page.getByLabel('Provincia de la comunidad')).toHaveValue('Guayas')
  await expect(page.getByLabel('Resumen territorial')).toContainText('Guayaquil')
  await expect(page.getByLabel('Resumen territorial')).not.toContainText('Quito')
  const errors=await page.evaluate(async()=>{
    const url='/src/features/communities/community-territory.ts'
    const {validateCommunityTerritory}=await import(url)
    return validateCommunityTerritory({province:'Guayas',cantonCode:'1701',parishCode:'170150',sector:''})
  })
  expect(errors['cw-cantonCode']).toContain('provincia seleccionada')
  expect(errors['cw-parishCode']).toContain('cantón seleccionado')
})

